    pub fn message(self, message: &str) -> String {
        if self == Self::English {
            return message.to_owned();
        }
        if let Some(amount) = message.strip_prefix("Downloading Ubuntu: ") {
            return format!("Đang tải Ubuntu: {amount}");
        }
        if let Some(tail) = message.strip_prefix("Creation failed: ") {
            return format!(
                "Tạo máy ảo thất bại: {}",
                self.message(tail)
                    .replace("Retained workspace:", "Thư mục được giữ lại:")
                    .replace("Originals are preserved.", "Dữ liệu gốc được giữ nguyên.")
            );
        }
        if let Some(details) = message.strip_prefix("VM storage insufficient: ") {
            return format!(
                "Không đủ chỗ trống để tạo máy ảo: {}",
                details
                    .replace("need ", "cần ")
                    .replace(
                        " MiB for initial creation/import, available ",
                        " MiB để tạo/nhập ban đầu, còn "
                    )
                    .replace(" MiB at ", " MiB tại ")
                    .replace(
                        "Select a destination with more free space.",
                        "Chọn nơi lưu có thêm chỗ trống."
                    )
                    .replace(
                        "The virtual disk grows as data is written.",
                        "Đĩa ảo tăng theo dữ liệu được ghi."
                    )
            );
        }
        for (english, vietnamese) in [
            ("Invalid settings JSON at line ", "JSON cấu hình không hợp lệ tại dòng "),
            ("Settings exported: ","Đã xuất cấu hình: "),
            ("VM storage insufficient: ","Không đủ dung lượng lưu trữ: "),
            ("Shared folder: ","Thư mục chia sẻ: "),
            ("installer: ","Bộ cài: "),
            ("variable template: ","Mẫu NVRAM: "),
            ("Settings saved for next start. Backup: ", "Đã lưu cho lần khởi động tới. Bản sao: "),
            ("Guest responded: ", "Máy ảo đã phản hồi: "),
            ("Guest reported process started (PID ", "Guest xác nhận tiến trình đã chạy (PID "),
            ("Guest request failed: ", "Yêu cầu tới guest thất bại: "),
            ("VM process ended (", "Tiến trình VM đã kết thúc ("),
            ("Mouse click sent. Check the updated display.", "Đã gửi nhấp chuột. Cập nhật màn hình để kiểm tra."),
            ("Guest shutdown requested. Refresh to check completion.", "Đã yêu cầu tắt máy. Cập nhật trạng thái để kiểm tra."),
            ("Force stop requested. Refresh to check completion.", "Đã yêu cầu buộc dừng. Cập nhật trạng thái để kiểm tra."),
            ("Status unavailable. If the VM is powered off, use Start; otherwise inspect its runtime log. Details: ", "Chưa đọc được trạng thái. Khởi động nếu VM đã tắt; nếu đang chạy, kiểm tra log. Chi tiết: "),
        ] {
            if let Some(tail) = message.strip_prefix(english) { return format!("{vietnamese}{tail}"); }
        }
        self.text(message).to_owned()
    }
